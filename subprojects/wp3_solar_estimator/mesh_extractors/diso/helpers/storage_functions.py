import os

import torch
import trimesh


def tensors_to_mesh(
    verts: torch.Tensor,
    faces: torch.Tensor,
    save_mesh: bool = True,
    filename: str = "loading_test.ply",
    mesh_dir: str | None = None,  # Default to None, not a space
    verbose: bool = True,
):
    """
    Pre: Vertices and Faces generated from kaolin/diso/other library functions (e.g. flexicubes or DiffMC)
    Post: Mesh generated by trimesh from these faces, saves it as a PLY file if save_mesh is True.



    Note that the PLY generation is not differentiable!
    This should be the end of the pipeline and serve only for visualization and Postprocessing of mesh
    """
    verts_np = verts.detach().cpu().numpy()
    faces_np = faces.detach().cpu().numpy()
    mesh = trimesh.Trimesh(vertices=verts_np, faces=faces_np, process=False)
    if save_mesh:
        if mesh_dir is not None:
            os.makedirs(mesh_dir, exist_ok=True)
            filepath = os.path.join(mesh_dir, filename)
        else:
            filepath = filename
        mesh.export(filepath)
        if verbose:
            print(f"Mesh saved to {filepath}")
        return mesh
    return mesh
